// Your crew: life 1 is your chosen look, lives 2 and 3 are crewmates.
export function crewFor(look = 0, hair = 0, skin = 1) {
  return [0, 2, 4].map((step, i) => ({
    look: (look + step) % LOOKS.length,
    hair: (hair + i * 2) % HAIR_COLORS.length,
    skin: (skin + i * 2) % SKIN_TONES.length,
    name: i === 0 ? 'YOU' : ['CREW: DEV', 'CREW: RIO'][i - 1],
  }));
}
